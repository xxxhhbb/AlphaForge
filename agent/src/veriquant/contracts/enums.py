class ContractValidationError(ValueError):
    """Fail-closed validation error with a machine-readable code."""

    def __init__(
        self,
        code: FailureCode,
        message: str,
        *,
        details: Mapping[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.details = MappingProxyType(dict(details or {}))

